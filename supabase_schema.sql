-- Optional production schema for American90.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  xp integer not null default 0,
  streak integer not null default 0,
  current_day integer not null default 1,
  created_at timestamptz not null default now()
);

create table if not exists public.lesson_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  day integer not null,
  score integer not null default 0,
  completed_at timestamptz not null default now(),
  unique(user_id, day)
);

create table if not exists public.review_cards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  term text not null,
  due_at timestamptz not null default now(),
  interval_days integer not null default 1,
  ease numeric not null default 2.5
);

alter table public.profiles enable row level security;
alter table public.lesson_results enable row level security;
alter table public.review_cards enable row level security;

create policy "own profile" on public.profiles for all using (auth.uid()=id) with check (auth.uid()=id);
create policy "own results" on public.lesson_results for all using (auth.uid()=user_id) with check (auth.uid()=user_id);
create policy "own cards" on public.review_cards for all using (auth.uid()=user_id) with check (auth.uid()=user_id);
